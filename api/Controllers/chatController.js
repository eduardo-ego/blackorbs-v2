import db from '../db/index.js';
import openai from '../AI/openai.js';
import claude from '../AI/claude.js';
import { formatearLocal } from '../utils/time.js';

const insertConsulta = db.prepare(`
  INSERT INTO consultas_ia (device_id, modelo, prompt, respuesta)
  VALUES (@device_id, @modelo, @prompt, @respuesta)
`);

// --- Herramientas que el LLM puede invocar. Todas son de solo lectura sobre
// datos que YA calculó el servicio de ML o el sensor; el LLM nunca deriva
// anomalías/forecast por su cuenta. Definidas una sola vez y adaptadas al
// formato de cada proveedor más abajo. ---

function getEstadoActual(deviceId) {
  const estado = db.prepare('SELECT * FROM ml_estado WHERE device_id = ?').get(deviceId) ||
    { mood: 'happy', message: 'No ML state calculated yet.' };
  return { ...estado, hora_local: formatearLocal(estado.updated_at) };
}

function getUltimaLectura(deviceId) {
  const lectura = db
    .prepare('SELECT * FROM lecturas WHERE device_id = ? ORDER BY timestamp DESC LIMIT 1')
    .get(deviceId);
  return lectura ? { ...lectura, hora_local: formatearLocal(lectura.timestamp) } : null;
}

function getHistorialLecturas(deviceId, minutos = 60) {
  const filas = db
    .prepare(
      `SELECT temperature, humidity, pressure, timestamp FROM lecturas
       WHERE device_id = ? AND timestamp >= datetime('now', ?)
       ORDER BY timestamp ASC`
    )
    .all(deviceId, `-${Number(minutos)} minutes`);
  return filas.map((f) => ({ ...f, hora_local: formatearLocal(f.timestamp) }));
}

function getAlertasRecientes(limit = 10) {
  const filas = db.prepare('SELECT * FROM alertas ORDER BY timestamp DESC LIMIT ?').all(limit);
  return filas.map((f) => ({ ...f, hora_local: formatearLocal(f.timestamp) }));
}

function ejecutarHerramienta(deviceId, nombre, args) {
  switch (nombre) {
    case 'get_estado_actual':
      return getEstadoActual(deviceId);
    case 'get_ultima_lectura':
      return getUltimaLectura(deviceId);
    case 'get_historial_lecturas':
      return getHistorialLecturas(deviceId, args.minutos);
    case 'get_alertas_recientes':
      return getAlertasRecientes(args.limit);
    default:
      return { error: `Unknown tool: ${nombre}` };
  }
}

const TOOLS_SPEC = [
  {
    name: 'get_estado_actual',
    description: 'Current state calculated by the ML system: mood (happy/attention/critical), anomaly score and active forecast.',
    parameters: { type: 'object', properties: {} },
  },
  {
    name: 'get_ultima_lectura',
    description: 'Latest raw sensor reading (temperature, humidity, pressure, timestamp).',
    parameters: { type: 'object', properties: {} },
  },
  {
    name: 'get_historial_lecturas',
    description: 'Sensor readings from the last N minutes, for trend questions.',
    parameters: {
      type: 'object',
      properties: { minutos: { type: 'number', description: 'Time window in minutes, default 60' } },
    },
  },
  {
    name: 'get_alertas_recientes',
    description: 'Recent alerts generated by the system.',
    parameters: {
      type: 'object',
      properties: { limit: { type: 'number', description: 'How many alerts to fetch, default 10' } },
    },
  },
];

const OPENAI_TOOLS = TOOLS_SPEC.map((t) => ({
  type: 'function',
  function: { name: t.name, description: t.description, parameters: t.parameters },
}));

const CLAUDE_TOOLS = TOOLS_SPEC.map((t) => ({
  name: t.name,
  description: t.description,
  input_schema: t.parameters,
}));

const SYSTEM_PROMPT = `You are the conversational assistant for this environmental monitoring device.
You have no way to measure or calculate anything yourself: all the intelligence (anomaly
detection and forecasting) was already calculated by a separate Machine Learning service
and lives in the tools available to you. Your only job is to: (1) understand what the
user is asking in natural language, (2) call the necessary tools to get the already
calculated data, and (3) answer briefly, clearly, and in English, without inventing
numbers that don't come from a tool. If you mention a time, always use the tool's
"hora_local" field (the device's timezone, America/Mexico_City) — never the
"timestamp"/"updated_at" field, which is in UTC and would confuse the user.`;

async function responderConOpenAI(message, deviceId) {
  const messages = [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'user', content: message },
  ];

  for (let i = 0; i < 4; i++) {
    const completion = await openai.chat.completions.create({
      model: 'gpt-4o',
      messages,
      tools: OPENAI_TOOLS,
      temperature: 0.2,
    });

    const choice = completion.choices[0].message;
    messages.push(choice);

    if (!choice.tool_calls?.length) {
      return choice.content;
    }

    for (const toolCall of choice.tool_calls) {
      const args = JSON.parse(toolCall.function.arguments || '{}');
      const resultado = ejecutarHerramienta(deviceId, toolCall.function.name, args);
      messages.push({ role: 'tool', tool_call_id: toolCall.id, content: JSON.stringify(resultado) });
    }
  }

  return "I couldn't get a clear answer, try rephrasing the question.";
}

async function responderConClaude(message, deviceId) {
  const messages = [{ role: 'user', content: message }];

  for (let i = 0; i < 4; i++) {
    const response = await claude.messages.create({
      model: 'claude-opus-5',
      max_tokens: 1024,
      system: SYSTEM_PROMPT,
      tools: CLAUDE_TOOLS,
      messages,
    });

    messages.push({ role: 'assistant', content: response.content });

    if (response.stop_reason !== 'tool_use') {
      const textBlock = response.content.find((b) => b.type === 'text');
      return textBlock ? textBlock.text : null;
    }

    const toolResults = [];
    for (const block of response.content) {
      if (block.type === 'tool_use') {
        const resultado = ejecutarHerramienta(deviceId, block.name, block.input || {});
        toolResults.push({ type: 'tool_result', tool_use_id: block.id, content: JSON.stringify(resultado) });
      }
    }
    messages.push({ role: 'user', content: toolResults });
  }

  return "I couldn't get a clear answer, try rephrasing the question.";
}

function mensajeDeError(err) {
  if (err.message?.includes('authentication method') || err.message?.includes('API_KEY')) {
    return 'This provider\'s API key is not configured in the .env file';
  }
  if (err.code === 'insufficient_quota' || err.error?.type === 'insufficient_quota') {
    return 'This provider\'s account has no active credits/billing.';
  }
  if (err.status === 401) return 'This provider\'s API key is not valid.';
  if (err.status === 429) return 'The provider\'s usage limit was reached, try again later.';
  return 'Error processing the message';
}

export const chat = async (req, res) => {
  const { message, provider = 'openai' } = req.body;
  const deviceId = req.app.get('deviceId');
  const io = req.app.get('io');

  if (!message || typeof message !== 'string') {
    return res.status(400).json({ error: 'Missing "message" in body' });
  }
  if (!['openai', 'claude'].includes(provider)) {
    return res.status(400).json({ error: 'provider must be "openai" or "claude"' });
  }

  io?.emit('chatMood', { mood: 'thinking' });

  try {
    const respuestaFinal =
      (provider === 'claude'
        ? await responderConClaude(message, deviceId)
        : await responderConOpenAI(message, deviceId)) ||
      "I couldn't get a clear answer, try rephrasing the question.";

    insertConsulta.run({ device_id: deviceId, modelo: provider, prompt: message, respuesta: respuestaFinal });

    const estado = getEstadoActual(deviceId);
    io?.emit('chatMood', { mood: estado.mood || 'happy' });

    res.json({ result: respuestaFinal, provider });
  } catch (err) {
    console.error(`❌ Error in chat (${provider}):`, err);
    io?.emit('chatMood', { mood: 'happy' });
    res.status(500).json({ error: mensajeDeError(err) });
  }
};

export const getChatHistory = async (req, res) => {
  try {
    const deviceId = req.app.get('deviceId');
    const limit = Number(req.query.limit) || 50;
    const historial = db
      .prepare('SELECT * FROM consultas_ia WHERE device_id = ? ORDER BY timestamp DESC LIMIT ?')
      .all(deviceId, limit);
    res.json(historial);
  } catch (err) {
    res.status(500).json({ error: 'Error fetching chat history' });
  }
};
